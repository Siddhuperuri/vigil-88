"""Measure the P3 event chain's cost, in isolation from inference.

    uv run python scripts/measure_p3.py

The temporal engine is meant to be lightweight *relative to neural inference* (04 §2: the
narrow stages can afford to be careful because the wide ones dominate). This script measures
whether that holds, by driving the real chain with scripted scenes and no model.

It deliberately does not write `docs/PERFORMANCE.md`. That file is generated by `vigil bench`
from camera and inference runs, and is the only place permitted to make a performance claim
(README rule 2); this is a developer measurement of one stage, reported as such.

Wall-clock reads here are measurement, not decision logic, so they carry the gate's opt-out.
"""

from __future__ import annotations

import gc
import statistics
import sys
import time  # gate: allow measuring elapsed time in a benchmark script
import tracemalloc
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from tests.support.replay import Replay, settings_for, walk
from tests.support.scenes import SceneStateBuilder

from vigil.domain.enums import ObjectClass, ZoneKind

PERCENTILES = (50, 95, 99)


def percentile(values: list[float], p: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    index = min(round(p / 100.0 * (len(ordered) - 1)), len(ordered) - 1)
    return ordered[index]


def summarise(name: str, samples_ms: list[float], *, per: str = "tick") -> None:
    print(f"\n{name}")
    print(f"  samples        {len(samples_ms)}")
    print(f"  mean           {statistics.fmean(samples_ms) * 1000:.1f} us/{per}")
    for p in PERCENTILES:
        print(f"  p{p:<13}{percentile(samples_ms, p) * 1000:.1f} us/{per}")
    print(f"  max            {max(samples_ms) * 1000:.1f} us/{per}")


def measure_chain(*, tracks: int, frames: int) -> list[float]:
    """One camera, `tracks` people inside a restricted zone, `frames` analysed frames."""
    run = Replay()
    scenes = []
    for index in range(frames):
        t_ms = index * 100.0
        builder = SceneStateBuilder(camera_id="test-cam").with_zone(
            "yard", ZoneKind.RESTRICTED, criticality=3
        )
        for track_id in range(tracks):
            builder.with_track(
                track_id,
                ObjectClass.PERSON,
                at=(0.6 + 0.01 * (track_id % 20), 0.6),
                hits=index + 1,
                age_frames=index + 1,
                in_zones=["yard"],
                dwell_ms={"yard": t_ms},
                first_seen_ms=0.0,
                velocity_px_s=(20.0, 0.0),
            )
        scenes.append(builder.at_time(t_ms, frame_index=index).build())

    samples: list[float] = []
    for scene in scenes:
        started = time.perf_counter()
        run.pipeline.process(scene)
        samples.append(time.perf_counter() - started)
    return samples


def measure_accumulator_only(*, observations: int) -> list[float]:
    """The temporal update rule alone: decay, clamp, add, bound, plus the support ratio."""
    from vigil.config.schema.modules import TemporalConfig
    from vigil.core.units import ms_to_ns
    from vigil.domain.observation import Observation, SubjectKey
    from vigil.temporal.accumulator import Accumulator

    subject = SubjectKey("track", "1")
    accumulator = Accumulator(
        camera_id="test-cam",
        module_id="intrusion",
        subject=subject,
        config=TemporalConfig(),
        support_slot_ms=100.0,
    )
    batch = [
        Observation(
            camera_id="test-cam",
            module_id="intrusion",
            subject=subject,
            signal=0.7,
            t_monotonic_ns=ms_to_ns(i * 100.0),
            facts={"zone_id": "yard"},
        )
        for i in range(observations)
    ]
    samples: list[float] = []
    for observation in batch:
        started = time.perf_counter()
        accumulator.observe(observation)
        samples.append(time.perf_counter() - started)
    return samples


def measure_memory(*, subjects: int) -> tuple[int, float]:
    """Peak accumulator count and retained KiB across many short-lived subjects."""
    from vigil.core.units import ms_to_ns
    from vigil.domain.observation import Observation, SubjectKey
    from vigil.temporal.store import AccumulatorStore

    settings = settings_for()
    store = AccumulatorStore(camera_id="test-cam", config=settings.temporal, support_slot_ms=100.0)
    gc.collect()
    tracemalloc.start()
    peak_count = 0
    for index in range(subjects):
        t_ms = index * 100.0
        store.decay_all_to(ms_to_ns(t_ms))
        store.observe(
            Observation(
                camera_id="test-cam",
                module_id="intrusion",
                subject=SubjectKey("track", str(index)),
                signal=0.8,
                t_monotonic_ns=ms_to_ns(t_ms),
                facts={"zone_id": "yard"},
            )
        )
        store.prune_idle(ms_to_ns(t_ms))
        peak_count = max(peak_count, len(store))
    current, _peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    return (peak_count, current / 1024.0)


def measure_outcomes() -> None:
    """Confirmed and rejected counts for the canonical scenarios."""
    print("\nevent rates (scripted scenarios, 10 fps)")
    cases = {
        "sustained intrusion, 30 s": walk(inside_until_ms=14_000.0, duration_ms=30_000.0),
        "brief crossing (300 ms)": walk(
            inside_from_ms=1000.0, inside_until_ms=1300.0, duration_ms=30_000.0
        ),
        "boundary loiter, 60 s": None,
        "unstable scene, 20 s": walk(
            inside_until_ms=None, duration_ms=20_000.0, stability_ratio=0.1
        ),
    }
    from tests.integration.test_intrusion_scenarios import boundary_loiter
    from tests.support.candidates import healthy

    cases["boundary loiter, 60 s"] = boundary_loiter(duration_ms=60_000.0)
    for name, scenes in cases.items():
        assert scenes is not None
        result = Replay(camera_health=healthy()).run(scenes)
        print(
            f"  {name:<28} observations {result.observations_total:>5}  "
            f"confirmed {len(result.scored):>2}  rejected {len(result.rejected):>2}  "
            f"released {len(result.released):>2}  peak candidates {result.peak_active_candidates}"
        )


def main() -> int:
    print("VIGIL-88 P3 event-chain measurement")
    print("This measures the P3 stages only. No model, no camera, no GPU.")

    summarise(
        "accumulator update (observe)", measure_accumulator_only(observations=20_000), per="obs"
    )

    for tracks in (1, 5, 20):
        samples = measure_chain(tracks=tracks, frames=600)
        summarise(f"full chain per analysed frame, {tracks} tracked subject(s) in zone", samples)

    for subjects in (1000, 10_000):
        count, kib = measure_memory(subjects=subjects)
        print(
            f"\nmemory, {subjects} short-lived subjects"
            f"\n  peak live accumulators  {count}"
            f"\n  retained after run      {kib:.0f} KiB"
        )

    measure_outcomes()
    print("\nNote: these are developer measurements of one stage on one machine, not a")
    print("performance claim. docs/PERFORMANCE.md is generated by `vigil bench`.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
