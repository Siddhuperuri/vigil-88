"""Lists every Python distribution that goes into the frozen engine, with its declared licence.

    python scripts/notices.py <python of the build venv> > docs/THIRD-PARTY-NOTICES.md

It reads metadata and does not judge it: a licence that is empty, or mentions a copyleft family, is
flagged for a person to read. The licence text of each package ships inside the package.
"""

from __future__ import annotations

import json
import subprocess
import sys

# Run inside the build venv, where the packages are installed.
READER = """
import json, importlib.metadata as m
rows = []
for d in m.distributions():
    md = d.metadata
    classifiers = [
        c.split("::")[-1].strip()
        for c in md.get_all("Classifier") or []
        if c.startswith("License ::")
    ]
    text = md.get("License") or ""
    if len(text) > 80:
        text = text.splitlines()[0][:80] + " ..."
    rows.append({
        "name": md["Name"],
        "version": d.version,
        "expression": md.get("License-Expression") or "",
        "license": text,
        "classifiers": classifiers,
    })
print(json.dumps(sorted(rows, key=lambda r: r["name"].lower())))
"""

# Build and packaging tools: they are not shipped.
SKIP = {
    "pip",
    "setuptools",
    "wheel",
    "pyinstaller",
    "pyinstaller-hooks-contrib",
    "altgraph",
    "pefile",
    "pywin32-ctypes",
    "packaging",
    "vigil-88",
}
COPYLEFT = ("gpl", "agpl", "lgpl", "mpl", "eupl", "cddl")

NOTES = """
## What the metadata does not show

- **FFmpeg inside OpenCV.** The OpenCV wheel ships `opencv_videoio_ffmpeg*.dll`, an FFmpeg build
  licensed LGPL-2.1-or-later. It is a separate file beside the engine, loaded at run time, so it can
  be replaced with another build of the same interface. The licence text is in the OpenCV wheel.
- **PyInstaller bootloader.** The engine executable embeds PyInstaller's bootloader, licensed
  GPL-2.0-or-later *with an exception* that permits distributing the frozen program under any
  licence. PyInstaller itself is a build tool and is not shipped. This does not make the product
  GPL, and it is recorded here so nobody has to rediscover it.
- **Electron and Chromium.** Their licences ship with the app (`LICENSE.electron.txt`,
  `LICENSES.chromium.html`). The console bundle contains React, React DOM and Zod (all MIT).
- **No NVIDIA runtime is shipped.** The installer carries the CPU engine only (plan decision 2).
- **The project's own licence is undeclared** (plan decision 1). Until it is chosen, nothing here
  grants anyone rights to VIGIL-88 itself.
"""


def declared(row: dict[str, object]) -> str:
    classifiers = row["classifiers"]
    joined = "; ".join(classifiers) if isinstance(classifiers, list) else ""
    return str(row["expression"] or row["license"] or joined or "(none declared)")


def main(python: str) -> None:
    # The interpreter is the build venv's own, named by the person running this script.
    run = subprocess.run(  # noqa: S603
        [python, "-c", READER], capture_output=True, text=True, check=True
    )
    rows = json.loads(run.stdout)
    print("# Third-party notices (Python engine)\n")
    print("Generated by `scripts/notices.py` from the packages frozen into the engine. The licence")
    print("text of each package is inside its own distribution. Build tools (PyInstaller and its")
    print("helpers) are not shipped and are omitted.\n")
    print("| Package | Version | Licence as declared | Needs a person to read |")
    print("|---|---|---|---|")
    for row in rows:
        if str(row["name"]).lower() in SKIP:
            continue
        text = declared(row)
        low = text.lower()
        flag = "yes" if text == "(none declared)" or any(w in low for w in COPYLEFT) else ""
        print(f"| {row['name']} | {row['version']} | {text.replace('|', '/')} | {flag} |")
    print(NOTES)


if __name__ == "__main__":
    main(sys.argv[1])
